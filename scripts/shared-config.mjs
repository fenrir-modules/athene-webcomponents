#!/usr/bin/env node
// Shared frontend tooling config: drift check (quality step 1.3).
//
// athene-webcomponents is the canonical home of the lint/format config that
// both frontends use; athene-web keeps byte-identical copies at the same
// paths. Why copies and not a package: each repo's CI checks out only itself,
// the app installs the lib from a git tag whose package ships only `dist/`, and
// lint rules should not wait for a lib release. The copies are guarded instead:
//
//   node scripts/shared-config.mjs            check (part of `npm run lint`)
//     - every shared file matches config/shared-config.lock.json (sha256), so
//       a copy edited in place fails, on CI too;
//     - in the app, when the lib checkout is present (../athene-webcomponents
//       or $ATHENE_WEBCOMPONENTS_DIR), the lock files must be equal, so the app
//       notices when the lib moved on.
//   node scripts/shared-config.mjs --write             (lib) re-hash after editing a shared file
//   node scripts/shared-config.mjs --copy-to ../athene-web   (lib) copy files + lock to the app
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SHARED_FILES = [
  '.prettierrc',
  'config/eslint.shared.mjs',
  'config/stylelint.shared.mjs',
  'scripts/stylelint/athene-tokens.mjs',
  'scripts/stylelint/angular-inline-styles.mjs',
  'scripts/knip-check.mjs',
  'scripts/shared-config.mjs',
];
const LOCK = 'config/shared-config.lock.json';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const isLib =
  JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).name === '@athene/webcomponents';
const args = process.argv.slice(2);
const sha = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');
const hashes = (dir) =>
  Object.fromEntries(
    SHARED_FILES.map((f) => [f, existsSync(join(dir, f)) ? sha(join(dir, f)) : null])
  );
const readLock = (dir) =>
  existsSync(join(dir, LOCK)) ? JSON.parse(readFileSync(join(dir, LOCK), 'utf8')).files : null;
const writeLock = (dir, files) =>
  writeFileSync(
    join(dir, LOCK),
    JSON.stringify(
      {
        $comment: 'Generated by scripts/shared-config.mjs in athene-webcomponents. Do not edit.',
        files,
      },
      null,
      2
    ) + '\n'
  );

if (args.includes('--write') || args.includes('--copy-to')) {
  if (!isLib) {
    console.error(
      'shared-config: --write/--copy-to run in athene-webcomponents (the canonical copy).'
    );
    process.exit(2);
  }
  const files = hashes(ROOT);
  writeLock(ROOT, files);
  console.log(`shared-config: ${LOCK} written`);
  const at = args.indexOf('--copy-to');
  if (at >= 0) {
    const target = resolve(args[at + 1] ?? '../athene-web');
    for (const f of [...SHARED_FILES, LOCK]) {
      mkdirSync(dirname(join(target, f)), { recursive: true });
      copyFileSync(join(ROOT, f), join(target, f));
    }
    console.log(`shared-config: ${SHARED_FILES.length} files + lock copied to ${target}`);
  }
  process.exit(0);
}

const errors = [];
const lock = readLock(ROOT);
if (!lock) errors.push(`${LOCK} is missing`);
else {
  const now = hashes(ROOT);
  for (const f of SHARED_FILES) {
    if (now[f] !== lock[f]) {
      errors.push(
        isLib
          ? `${f} changed: run \`node scripts/shared-config.mjs --copy-to ../athene-web\` (re-hashes and syncs the app)`
          : `${f} differs from the shared copy: edit it in athene-webcomponents and copy it over, never here`
      );
    }
  }
}

const peer = isLib
  ? resolve(process.env.ATHENE_WEB_DIR ?? join(ROOT, '../athene-web'))
  : resolve(process.env.ATHENE_WEBCOMPONENTS_DIR ?? join(ROOT, '../athene-webcomponents'));
const peerLock = existsSync(peer) ? readLock(peer) : null;
let note = 'peer checkout not found, compared against own lock only';
if (peerLock && lock) {
  const differs = SHARED_FILES.filter((f) => peerLock[f] !== lock[f]);
  if (!differs.length) note = `in sync with ${relative(ROOT, peer) || peer}`;
  else if (isLib) note = `athene-web is behind on ${differs.join(', ')} (copy with --copy-to)`;
  else
    errors.push(
      `out of date with ${peer}: ${differs.join(', ')} — run \`node ${relative(ROOT, join(peer, 'scripts/shared-config.mjs'))} --copy-to .\` from here`
    );
}

if (errors.length) {
  for (const e of errors) console.error(`shared-config: ${e}`);
  process.exit(1);
}
console.log(`shared-config: ${SHARED_FILES.length} shared files ok (${note})`);
